import type { PlayerInput } from "@application/commands/addPlayersCommand.js";
import type {
  GameState,
  GameWithNextAction,
  GameWithNextStep,
  Position,
  Rotation,
} from "@core/domain/types/index.js";
import type { GameEngine } from "@core/portUserside/engine.js";

// ─── Types ──────────────────────────────────────────────────────────

/**
 * Current action log format version.
 *
 * - `1` (or no `version` field): legacy logs. `createGame` may omit the seed,
 *   player ids and lord ids are not recorded, so a replay regenerates them.
 * - `2`: the effective seed, the game id, the player ids and the lord ids are
 *   recorded, so a replay reproduces a strictly identical game state.
 *
 * Version 1 logs remain replayable.
 */
export const ACTION_LOG_VERSION = 2;

/**
 * The types of state-changing actions that can be recorded.
 */
export type ActionType =
  | "createGame"
  | "addPlayers"
  | "addExtraRules"
  | "startGame"
  | "chooseDomino"
  | "placeDomino"
  | "discardDomino"
  | "placeGiant"
  | "sendGiant"
  | "placeKnight"
  | "constructBuilding"
  | "useDragon"
  | "placeFireToken"
  | "recruitCaveman"
  | "skipOptionalAction";

/**
 * Payload types for each action, containing only the command parameters
 * (excluding the game state, which is too large to store), plus the ids the
 * engine generated so that a replay reproduces them.
 */
export type ActionPayloadMap = {
  createGame: {
    mode: string;
    /** Effective seed of the game (generated by the engine when the caller gave none) */
    seed?: string;
    /** Id the engine generated for the game (restored on replay) */
    gameId?: string;
  };
  /**
   * Players as `{ id, name, bot? }` objects carrying the ids the engine
   * assigned (legacy logs may contain plain names).
   */
  addPlayers: { players: PlayerInput[] };
  addExtraRules: { extraRules: string[] };
  startGame: {
    /** Ids of the lords, in `game.lords` order (restored on replay) */
    lordIds?: string[];
  };
  chooseDomino: { lordId: string; dominoPick: number };
  placeDomino: { lordId: string; position: Position; rotation: Rotation };
  discardDomino: { lordId: string };
  /**
   * `lordId` is the lord that played the action: the current lord, or a lord
   * of the targeted player when it places a giant sent by an opponent.
   */
  placeGiant: { lordId: string; position: Position };
  sendGiant: {
    lordId: string;
    giantIndex: number;
    targetPlayerId: string;
    targetCrownPosition?: Position;
  };
  placeKnight: { lordId: string; position: Position };
  constructBuilding: {
    lordId: string;
    buildingId: number;
    position: Position;
  };
  useDragon: { lordId: string; buildingId: number };
  placeFireToken: { lordId: string; position: Position };
  recruitCaveman: {
    lordId: string;
    cavemanId: number;
    position: Position;
    resourcePositions: Position[];
  };
  skipOptionalAction: { lordId: string };
};

/**
 * A single recorded action in the game log.
 */
export type ActionEntry<T extends ActionType = ActionType> = {
  /** Auto-incrementing index (0-based) */
  id: number;
  /** Timestamp when the action was recorded (Date.now()) */
  timestamp: number;
  /** The type of action performed */
  action: T;
  /** Command parameters (excludes game state) */
  payload: ActionPayloadMap[T];
  /** Turn number after the action was applied */
  turn: number;
};

/**
 * An immutable log of all actions performed during a game.
 * Can be used to replay a game or analyze player decisions.
 * It is plain JSON: persist it with `JSON.stringify` and read it back with
 * `JSON.parse`.
 *
 * @example
 * ```typescript
 * const { engine, getLog } = wrapWithActionLog(baseEngine);
 * let game = engine.createGame({ mode: 'Classic' });
 * game = engine.addPlayers({ game, players: ['Alice', 'Bob'] });
 * // ... play the game ...
 * const log = getLog();
 * console.log(log.entries); // all actions recorded
 * ```
 */
export type GameActionLog = {
  /** Format version (see `ACTION_LOG_VERSION`); absent in legacy logs (version 1) */
  version?: number;
  /** The game ID this log belongs to */
  gameId: string;
  /** Immutable array of recorded actions */
  entries: readonly ActionEntry[];
};

// ─── Construction ───────────────────────────────────────────────────

/**
 * Creates an empty action log for a game.
 */
export const createActionLog = (gameId: string): GameActionLog => ({
  version: ACTION_LOG_VERSION,
  gameId,
  entries: [],
});

/**
 * Appends an action to the log (immutable — returns a new log).
 */
export const appendAction = (
  log: GameActionLog,
  entry: Omit<ActionEntry, "id" | "timestamp">,
): GameActionLog => ({
  ...log,
  entries: [
    ...log.entries,
    {
      ...entry,
      id: log.entries.length,
      timestamp: Date.now(),
    },
  ],
});

// ─── Queries ────────────────────────────────────────────────────────

/**
 * Returns all entries in the log.
 */
export const getActions = (log: GameActionLog): readonly ActionEntry[] =>
  log.entries;

/**
 * Returns entries filtered by action type.
 */
export const getActionsByType = (
  log: GameActionLog,
  type: ActionType,
): readonly ActionEntry[] => log.entries.filter((e) => e.action === type);

/**
 * Returns entries filtered by turn number.
 */
export const getActionsByTurn = (
  log: GameActionLog,
  turn: number,
): readonly ActionEntry[] => log.entries.filter((e) => e.turn === turn);

// ─── Engine Wrapper ─────────────────────────────────────────────────

/**
 * Wraps a GameEngine to automatically record every state-changing action.
 * Read-only methods are passed through unchanged.
 *
 * @param engine - The base game engine to wrap
 * @returns An object with the wrapped engine and a getLog() accessor
 *
 * @example
 * ```typescript
 * const { engine: logged, getLog } = wrapWithActionLog(baseEngine);
 * let game = logged.createGame({ mode: 'Classic' });
 * // ... play ...
 * const log = getLog(); // retrieve the full action log
 * ```
 */
export const wrapWithActionLog = (
  engine: GameEngine,
): { engine: GameEngine; getLog: () => GameActionLog } => {
  let log = createActionLog("");

  const record = <T extends ActionType>(
    action: T,
    payload: ActionPayloadMap[T],
    turn: number,
  ): void => {
    log = appendAction(log, { action, payload, turn });
  };

  const wrappedEngine: GameEngine = {
    // Read-only methods — pass through
    getModes: (cmd) => engine.getModes(cmd),
    getExtraRules: (cmd) => engine.getExtraRules(cmd),
    calculateScore: (cmd) => engine.calculateScore(cmd),
    getValidPlacements: (cmd) => engine.getValidPlacements(cmd),
    canPlaceDomino: (cmd) => engine.canPlaceDomino(cmd),
    serialize: (cmd) => engine.serialize(cmd),
    deserialize: (cmd) => engine.deserialize(cmd),
    getResults: (cmd) => engine.getResults(cmd),
    getDynastyResults: (cmd) => engine.getDynastyResults(cmd),
    calculatePlayerScore: (cmd) => engine.calculatePlayerScore(cmd),

    // State-changing methods — record after execution
    createGame: (cmd) => {
      const game = engine.createGame(cmd);
      log = createActionLog(game.id);
      record(
        "createGame",
        { mode: cmd.mode, seed: game.seed ?? cmd.seed, gameId: game.id },
        game.turn,
      );
      return game;
    },

    addPlayers: (cmd) => {
      const game = engine.addPlayers(cmd);
      record(
        "addPlayers",
        {
          players: game.players.map((player) => ({
            id: player.id,
            name: player.name,
            ...(player.bot && { bot: player.bot }),
          })),
        },
        game.turn,
      );
      return game;
    },

    addExtraRules: (cmd) => {
      const game = engine.addExtraRules(cmd);
      record("addExtraRules", { extraRules: cmd.extraRules }, game.turn);
      return game;
    },

    startGame: (cmd) => {
      const game = engine.startGame(cmd);
      record(
        "startGame",
        { lordIds: game.lords.map((lord) => lord.id) },
        game.turn,
      );
      return game;
    },

    chooseDomino: (cmd) => {
      const game = engine.chooseDomino(cmd);
      record(
        "chooseDomino",
        { lordId: cmd.lordId, dominoPick: cmd.dominoPick },
        game.turn,
      );
      return game;
    },

    placeDomino: (cmd) => {
      const game = engine.placeDomino(cmd);
      record(
        "placeDomino",
        {
          lordId: cmd.lordId,
          position: cmd.position,
          rotation: cmd.rotation,
        },
        game.turn,
      );
      return game;
    },

    discardDomino: (cmd) => {
      const game = engine.discardDomino(cmd);
      record("discardDomino", { lordId: cmd.lordId }, game.turn);
      return game;
    },

    // Queendomino methods — record after execution
    placeKnight: (cmd) => {
      const game = engine.placeKnight(cmd);
      record(
        "placeKnight",
        { lordId: cmd.lordId, position: cmd.position },
        game.turn,
      );
      return game;
    },

    constructBuilding: (cmd) => {
      const game = engine.constructBuilding(cmd);
      record(
        "constructBuilding",
        {
          lordId: cmd.lordId,
          buildingId: cmd.buildingId,
          position: cmd.position,
        },
        game.turn,
      );
      return game;
    },

    useDragon: (cmd) => {
      const game = engine.useDragon(cmd);
      record(
        "useDragon",
        { lordId: cmd.lordId, buildingId: cmd.buildingId },
        game.turn,
      );
      return game;
    },

    skipOptionalAction: (cmd) => {
      const game = engine.skipOptionalAction(cmd);
      record("skipOptionalAction", { lordId: cmd.lordId }, game.turn);
      return game;
    },

    // Origins methods — record after execution
    placeFireToken: (cmd) => {
      const game = engine.placeFireToken(cmd);
      record(
        "placeFireToken",
        { lordId: cmd.lordId, position: cmd.position },
        game.turn,
      );
      return game;
    },

    recruitCaveman: (cmd) => {
      const game = engine.recruitCaveman(cmd);
      record(
        "recruitCaveman",
        {
          lordId: cmd.lordId,
          cavemanId: cmd.cavemanId,
          position: cmd.position,
          resourcePositions: cmd.resourcePositions,
        },
        game.turn,
      );
      return game;
    },

    // Age of Giants methods — record after execution
    placeGiant: (cmd) => {
      const game = engine.placeGiant(cmd);
      record(
        "placeGiant",
        { lordId: cmd.lordId, position: cmd.position },
        game.turn,
      );
      return game;
    },

    sendGiant: (cmd) => {
      const game = engine.sendGiant(cmd);
      record(
        "sendGiant",
        {
          lordId: cmd.lordId,
          giantIndex: cmd.giantIndex,
          targetPlayerId: cmd.targetPlayerId,
          ...(cmd.targetCrownPosition !== undefined && {
            targetCrownPosition: cmd.targetCrownPosition,
          }),
        },
        game.turn,
      );
      return game;
    },

    // Valid targets for extension actions — read-only, pass through
    getValidFireTokenPositions: (cmd) => engine.getValidFireTokenPositions(cmd),
    getValidKnightPositions: (cmd) => engine.getValidKnightPositions(cmd),
    getValidBuildingPositions: (cmd) => engine.getValidBuildingPositions(cmd),
    getAffordableBuildings: (cmd) => engine.getAffordableBuildings(cmd),
    getValidCavemanPlacements: (cmd) => engine.getValidCavemanPlacements(cmd),
    getValidGiantPositions: (cmd) => engine.getValidGiantPositions(cmd),
    getValidGiantTargets: (cmd) => engine.getValidGiantTargets(cmd),
    canSkipOptionalAction: (cmd) => engine.canSkipOptionalAction(cmd),
  };

  return {
    engine: wrappedEngine,
    getLog: () => log,
  };
};

// ─── Replay ─────────────────────────────────────────────────────────

/**
 * Restores the lord ids recorded by `startGame`. Lords are created and
 * shuffled deterministically (seeded shuffle), so the replayed lords match the
 * recorded ones position by position; only their generated ids differ.
 * Right after `startGame`, lord ids only appear in `lords` and `nextAction`.
 */
const restoreLordIds = (
  game: GameWithNextAction,
  lordIds: readonly string[] | undefined,
): GameWithNextAction => {
  if (!lordIds || lordIds.length !== game.lords.length) return game;

  const idMap = new Map<string, string>();
  game.lords.forEach((lord, index) => {
    idMap.set(lord.id, lordIds[index] as string);
  });
  const mapId = (id: string): string => idMap.get(id) ?? id;

  return {
    ...game,
    lords: game.lords.map((lord) => ({ ...lord, id: mapId(lord.id) })),
    currentDominoes: game.currentDominoes.map((domino) =>
      domino.lordId ? { ...domino, lordId: mapId(domino.lordId) } : domino,
    ),
    nextAction: {
      ...game.nextAction,
      nextLord: mapId(game.nextAction.nextLord),
    },
  };
};

/**
 * Replays a `createGame` entry, restoring the recorded game id.
 */
const replayCreateGame = (
  engine: GameEngine,
  payload: ActionPayloadMap["createGame"],
): GameWithNextStep => {
  const game = engine.createGame({ mode: payload.mode, seed: payload.seed });
  return payload.gameId ? { ...game, id: payload.gameId } : game;
};

/**
 * Applies a single recorded action to a game state.
 */
const applyEntry = (
  engine: GameEngine,
  game: GameState,
  entry: ActionEntry,
): GameState => {
  switch (entry.action) {
    case "createGame":
      return replayCreateGame(
        engine,
        entry.payload as ActionPayloadMap["createGame"],
      );
    case "addPlayers": {
      const payload = entry.payload as ActionPayloadMap["addPlayers"];
      return engine.addPlayers({ game, players: payload.players });
    }
    case "addExtraRules": {
      const payload = entry.payload as ActionPayloadMap["addExtraRules"];
      return engine.addExtraRules({ game, extraRules: payload.extraRules });
    }
    case "startGame": {
      const payload = entry.payload as ActionPayloadMap["startGame"];
      return restoreLordIds(engine.startGame({ game }), payload.lordIds);
    }
    case "chooseDomino": {
      const payload = entry.payload as ActionPayloadMap["chooseDomino"];
      return engine.chooseDomino({
        game,
        lordId: payload.lordId,
        dominoPick: payload.dominoPick,
      });
    }
    case "placeDomino": {
      const payload = entry.payload as ActionPayloadMap["placeDomino"];
      return engine.placeDomino({
        game,
        lordId: payload.lordId,
        position: payload.position,
        rotation: payload.rotation,
      });
    }
    case "discardDomino": {
      const payload = entry.payload as ActionPayloadMap["discardDomino"];
      return engine.discardDomino({ game, lordId: payload.lordId });
    }
    case "placeGiant": {
      const payload = entry.payload as ActionPayloadMap["placeGiant"];
      return engine.placeGiant({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        position: payload.position,
      });
    }
    case "sendGiant": {
      const payload = entry.payload as ActionPayloadMap["sendGiant"];
      return engine.sendGiant({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        giantIndex: payload.giantIndex,
        targetPlayerId: payload.targetPlayerId,
        ...(payload.targetCrownPosition !== undefined && {
          targetCrownPosition: payload.targetCrownPosition,
        }),
      });
    }
    case "placeKnight": {
      const payload = entry.payload as ActionPayloadMap["placeKnight"];
      return engine.placeKnight({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        position: payload.position,
      });
    }
    case "constructBuilding": {
      const payload = entry.payload as ActionPayloadMap["constructBuilding"];
      return engine.constructBuilding({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        buildingId: payload.buildingId,
        position: payload.position,
      });
    }
    case "useDragon": {
      const payload = entry.payload as ActionPayloadMap["useDragon"];
      return engine.useDragon({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        buildingId: payload.buildingId,
      });
    }
    case "placeFireToken": {
      const payload = entry.payload as ActionPayloadMap["placeFireToken"];
      return engine.placeFireToken({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        position: payload.position,
      });
    }
    case "recruitCaveman": {
      const payload = entry.payload as ActionPayloadMap["recruitCaveman"];
      return engine.recruitCaveman({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
        cavemanId: payload.cavemanId,
        position: payload.position,
        resourcePositions: payload.resourcePositions,
      });
    }
    case "skipOptionalAction": {
      const payload = entry.payload as ActionPayloadMap["skipOptionalAction"];
      return engine.skipOptionalAction({
        game: game as GameWithNextAction,
        lordId: payload.lordId,
      });
    }
    default:
      throw new Error(
        `Unknown action in action log: ${String((entry as ActionEntry).action)}`,
      );
  }
};

/**
 * Replays all actions from a log on a fresh engine to reconstruct the final game state.
 *
 * Version 2 logs (see `ACTION_LOG_VERSION`) record the effective seed and every
 * generated id (game, players, lords), so the replayed state is strictly
 * identical to the original one, whatever the replay engine's `uuidMethod`
 * and `shuffleMethod`. Legacy logs (version 1) are still replayed; their ids
 * are regenerated, and when they lack a seed the replay engine should use the
 * same configuration (especially shuffleMethod) as the original game.
 *
 * @param engine - A game engine instance
 * @param log - The action log to replay
 * @returns The final game state after replaying all actions
 * @throws Error if the log is empty, does not start with createGame, or has an unsupported version
 */
export const replayActions = (
  engine: GameEngine,
  log: GameActionLog,
): GameState => {
  if (log.entries.length === 0) {
    throw new Error("Cannot replay an empty action log");
  }

  if (log.version !== undefined && log.version > ACTION_LOG_VERSION) {
    throw new Error(
      `Unsupported action log version: ${log.version}. Current version: ${ACTION_LOG_VERSION}`,
    );
  }

  const firstEntry = log.entries[0];
  if (firstEntry?.action !== "createGame") {
    throw new Error("Action log must start with a createGame action");
  }

  let game: GameState = replayCreateGame(
    engine,
    firstEntry.payload as ActionPayloadMap["createGame"],
  );

  for (let i = 1; i < log.entries.length; i++) {
    const entry = log.entries[i];
    if (!entry) continue;
    game = applyEntry(engine, game, entry);
  }

  return game;
};
